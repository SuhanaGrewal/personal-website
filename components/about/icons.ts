/* ── platform marks, as 21x21 pixel bitmaps ──────────────────
   drawn as grids rather than borrowed logo assets, in the same
   dot-matrix language as a real LED sign — the technique the
   reference used, applied to suhana's actual four platforms
   rather than the reference's own. each row is a string of
   21 characters; '#' is a lit dot, '.' is dark board underneath
   it. generated and verified programmatically (row/gap counts
   checked in code, not eyeballed) rather than hand-drawn ascii,
   since a single wrong character silently misshapes the glyph.
   ────────────────────────────────────────────────────────── */

